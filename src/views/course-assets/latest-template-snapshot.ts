export function applyLatestTemplateSnapshot(templates: CourseTemplate[]): CourseTemplate[] {
  const byId = new Map(snapshot.map(item => [item.templateId, item]));
  return templates.map(template => {
    const latest = byId.get(template.id);
    if (!latest) return template;
    const priorUnits = new Map(template.units.map(unit => [unit.unitId, unit]));
    return {
      ...template,
      name: latest.name || template.name,
      units: latest.units.map((unit, index) => ({
        // Unit IDs may be replaced by a template revision. Do not carry path/PPT
        // fields from the former Unit: they are content-specific and become stale.
        ...(priorUnits.has(unit.unitId) ? priorUnits.get(unit.unitId) : {}),
        ...unit,
        order: index + 1,
        contentType: unit.contentType as CourseUnit["contentType"],
        pathSummary: priorUnits.get(unit.unitId)?.pathSummary || "待补充路径信息",
      })),
    };
  });
}
